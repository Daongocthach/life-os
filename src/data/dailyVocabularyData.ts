// Helper function to get pack for any day number (cycles gracefully or returns specific day)
export function getDailyVocabPack(dayNumber: number): DailyVocabPack {
  const index = ((dayNumber - 1) % DAILY_VOCAB_PACKS.length + DAILY_VOCAB_PACKS.length) % DAILY_VOCAB_PACKS.length
  const basePack = DAILY_VOCAB_PACKS[index]
  return {
    ...basePack,
    day: dayNumber,
  }
}

// Get the day index for today based on calendar or start epoch
export function getTodayDayIndex(): number {
  const startEpoch = new Date(2026, 0, 1).getTime() // Anchor Jan 1, 2026
  const now = new Date().getTime()
  const diffDays = Math.floor((now - startEpoch) / (1000 * 60 * 60 * 24))
  return Math.max(1, (diffDays % 30) + 1)
}
